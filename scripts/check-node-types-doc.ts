#!/usr/bin/env bun
// Keeps the per-type reference, `packages/core/shape-record/node-types.md`,
// equal to the core node types the code ships (ADR-086).
//
// The sheet is generated from what `packages/core/examples/dump_core_schemas.rs`
// prints (the `CoreNodeType` registry and `get_core_schemas()`): the registry
// table lists every concrete core type, abstract base and core subtype under
// its kind, and each type has a section whose field table lists exactly the
// fields the type's own schema declares, with each field's storage key
// (`<type>.<field>`), its type and, for an enum, its values in order and
// whether it is extensible or closed.
//
//   bun run node-types:gen     regenerate the committed sheet
//   bun run node-types:check   fail when the committed sheet differs from what
//                              the registry and the seeded schemas generate
//
// The merge gate and `bun run test:changed` run the check. Nothing is read
// from outside this checkout, so a change to a core type commits its
// regenerated sheet in the same change.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { $ } from "bun";

const REPO = join(dirname(new URL(import.meta.url).pathname), "..");

/** The committed sheet, relative to the repository root. */
export const SHEET_PATH = "packages/core/shape-record/node-types.md";

export type RegistryKind = "concrete" | "abstract_base" | "core_subtype";

/** One core type, as the registry records it. */
export interface DumpedType {
  id: string;
  kind: RegistryKind;
}

/** One field of a seeded schema: the parts the reference documents. */
export interface DumpedField {
  name: string;
  type: string;
  itemType?: string;
  coreValues?: { value: string }[];
  extensible?: boolean;
}

export interface DumpedSchema {
  id: string;
  fields: DumpedField[];
}

/** What `dump_core_schemas` prints. */
export interface CoreSchemaDump {
  types: DumpedType[];
  schemas: DumpedSchema[];
}

/** The registry table's row label for each kind. */
const KIND_ROWS: Record<RegistryKind, string> = {
  concrete: "Concrete core types",
  abstract_base: "Abstract bases",
  core_subtype: "Core subtypes",
};

function describeType(type: string, itemType?: string): string {
  return itemType === undefined ? type : `${type} of ${itemType}`;
}

function fieldRow(typeId: string, field: DumpedField): string {
  const isEnum = field.type === "enum";
  const type = isEnum ? `enum, ${field.extensible ? "extensible" : "closed"}` : describeType(field.type, field.itemType);
  const values = isEnum ? (field.coreValues ?? []).map((value) => `\`${value.value}\``).join(", ") : "";
  return `| \`${field.name}\` | \`${typeId}.${field.name}\` | ${type} |${values === "" ? "" : ` ${values}`} |`;
}

/** The reference sheet for a dump: the same text for the same registry and schemas. */
export function renderNodeTypesSheet(dump: CoreSchemaDump): string {
  const out: string[] = [
    "# Core node types",
    "",
    "<!-- Generated by `bun run node-types:gen` from the core type registry and the seeded core schemas. Do not edit by hand. -->",
    "",
    "## Registry",
    "",
    "| Kind | Types |",
    "|---|---|",
  ];
  for (const kind of Object.keys(KIND_ROWS) as RegistryKind[]) {
    const ids = dump.types.filter((type) => type.kind === kind).map((type) => type.id);
    out.push(`| ${KIND_ROWS[kind]} | ${ids.join(", ")} |`);
  }
  out.push("", "## Types");
  for (const type of dump.types) {
    out.push("", `### \`${type.id}\``, "");
    const schema = dump.schemas.find((candidate) => candidate.id === type.id);
    if (schema === undefined) {
      out.push("No seeded schema.");
      continue;
    }
    if (schema.fields.length === 0) {
      out.push("No fields of its own.");
      continue;
    }
    out.push("| Field | Storage | Type | Values |", "|---|---|---|---|");
    for (const field of schema.fields) out.push(fieldRow(type.id, field));
  }
  return `${out.join("\n")}\n`;
}

/**
 * One message per seeded schema whose id is not a registry type: the sheet is
 * rendered per registered type, so such a schema would otherwise go unlisted.
 */
export function unregisteredSchemas(dump: CoreSchemaDump): string[] {
  const registered = new Set(dump.types.map((type) => type.id));
  return dump.schemas
    .filter((schema) => !registered.has(schema.id))
    .map((schema) => `the code seeds a \`${schema.id}\` schema for a type the registry doesn't list`);
}

/** At most this many differing lines are listed per side. */
const MAX_LINES_PER_SIDE = 25;

/**
 * Every way the committed sheet and the generated one differ, one message each.
 * Empty when they match. `committed` is null when the file does not exist.
 */
export function compareNodeTypesSheet(committed: string | null, generated: string): string[] {
  if (committed === null) return [`${SHEET_PATH} does not exist.`];
  if (committed === generated) return [];
  const count = (text: string) => {
    const lines = new Map<string, number>();
    for (const line of text.split("\n")) lines.set(line, (lines.get(line) ?? 0) + 1);
    return lines;
  };
  const have = count(committed);
  const want = count(generated);
  const problems: string[] = [];
  const side = (against: Map<string, number>, text: string, say: (line: string) => string) => {
    const seen = new Map<string, number>();
    let listed = 0;
    for (const line of text.split("\n")) {
      const n = (seen.get(line) ?? 0) + 1;
      seen.set(line, n);
      if (n > (against.get(line) ?? 0) && line.trim() !== "") {
        if (listed++ < MAX_LINES_PER_SIDE) problems.push(say(line));
      }
    }
  };
  side(have, generated, (line) => `the code generates \`${line}\`, and the committed sheet lacks it`);
  side(want, committed, (line) => `the committed sheet has \`${line}\`, and the code no longer generates it`);
  if (problems.length === 0) problems.push("the committed sheet differs from the generated one in whitespace or line order");
  return problems;
}

async function dumpCoreSchemas(): Promise<CoreSchemaDump> {
  const dumped = await $`cargo run -q -p nodespace-core --example dump_core_schemas`.cwd(REPO).quiet().nothrow();
  if (dumped.exitCode !== 0) {
    console.error(`❌ Could not dump the core schemas:\n${dumped.stderr.toString()}`);
    process.exit(1);
  }
  return JSON.parse(dumped.stdout.toString()) as CoreSchemaDump;
}

if (import.meta.main) {
  const write = process.argv.includes("--write");
  const dump = await dumpCoreSchemas();
  const orphans = unregisteredSchemas(dump);
  if (orphans.length > 0) {
    console.error(`❌ The core schemas and the type registry disagree (${orphans.length}):`);
    for (const problem of orphans) console.error(`  - ${problem}`);
    process.exit(1);
  }
  const generated = renderNodeTypesSheet(dump);
  const path = join(REPO, SHEET_PATH);
  if (write) {
    writeFileSync(path, generated);
    console.log(`✅ Wrote ${SHEET_PATH} for ${dump.types.length} core node types.`);
    process.exit(0);
  }
  const problems = compareNodeTypesSheet(existsSync(path) ? readFileSync(path, "utf8") : null, generated);
  if (problems.length > 0) {
    console.error(`❌ ${SHEET_PATH} and the core node types disagree (${problems.length}):`);
    for (const problem of problems) console.error(`  - ${problem}`);
    console.error("\nRun `bun run node-types:gen` and commit the regenerated sheet with the type change (the node type sequence).");
    process.exit(1);
  }
  console.log(`✅ ${SHEET_PATH} matches the ${dump.types.length} core node types and their schemas.`);
}
